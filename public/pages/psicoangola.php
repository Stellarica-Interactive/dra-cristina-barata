<h2 id="psicoangola">PsicoAngola</h2>
Começou como simplesmente o projeto PsicoAngola no ano da pandemia COVID-19.<br>
Estávamos em plena pandemia quando me apercebi, vivendo em Portugal, que muito conteúdo no ocidente estava a ser produzido nas redes sociais sobre como lidar psicologicamente com a situação e no mundo angolano não via nada. Ao longo da minha formação e carreira já sabia que a psicologia estava muito subdesenvolvida em Angola e então decidi agir! Desde então fizemos parte da vida de 3000 pessoas.
<br>
<h3 style="text-align: center;">Voluntariado</h3>
Com a ajuda dos fantásticos mais de 30 voluntários que foram a alma do projeto e a minha sede por ajudar o máximo de angolanos possível, em 2024 tornámo-nos oficialmente uma <b class='golden-text'>clínica Angolana</b>.
